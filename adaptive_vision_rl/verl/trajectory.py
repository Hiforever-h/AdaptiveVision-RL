"""Recover trajectory-level semantics from verl-agent's step-expanded batch."""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any

from adaptive_vision_rl.dtpo_core import TrajectoryReward, assign_dtpo_rewards_and_advantages


@dataclass(frozen=True)
class TrajectoryView:
    row_indices: tuple[int, ...]
    tool_row: int | None
    answer_row: int
    reward: TrajectoryReward
    vision_tokens_low: int
    vision_tokens_crop: int
    vision_tokens_acquired: int
    vision_tokens_processed: int
    vision_tokens_full: int


def _as_dict(value: Any) -> dict[str, Any]:
    if isinstance(value, dict):
        return value
    if hasattr(value, "item"):
        unpacked = value.item()
        if isinstance(unpacked, dict):
            return unpacked
    raise TypeError(f"anchor_obs must be a dict, got {type(value)!r}")


def extract_trajectory_views(data, dtpo_config) -> list[TrajectoryView]:
    """Build unique trajectory records, excluding artificial divisor padding."""

    count = len(data)
    padding = data.non_tensor_batch.get("dtpo_padding", [False] * count)
    trajectory_ids = data.non_tensor_batch["traj_uid"]
    group_ids = data.non_tensor_batch["uid"]
    anchors = data.non_tensor_batch["anchor_obs"]
    step_rewards = data.non_tensor_batch["rewards"]

    rows_by_trajectory: dict[str, list[int]] = {}
    for index in range(count):
        if bool(padding[index]):
            continue
        rows_by_trajectory.setdefault(str(trajectory_ids[index]), []).append(index)

    partial: list[TrajectoryView] = []
    reward_records: list[TrajectoryReward] = []
    for trajectory_id, row_indices in rows_by_trajectory.items():
        decision_rows = [i for i in row_indices if _as_dict(anchors[i]).get("stage") == "decision"]
        answer_after_tool_rows = [
            i for i in row_indices if _as_dict(anchors[i]).get("stage") == "answer_after_tool"
        ]
        if len(decision_rows) != 1 or len(answer_after_tool_rows) > 1:
            raise ValueError(
                f"trajectory {trajectory_id} has invalid turn structure: "
                f"decision={decision_rows}, answer_after_tool={answer_after_tool_rows}"
            )

        used_tool = bool(answer_after_tool_rows)
        tool_row = decision_rows[0] if used_tool else None
        answer_row = answer_after_tool_rows[0] if used_tool else decision_rows[0]
        answer_base_reward = float(step_rewards[answer_row])
        accuracy = 1.0 if answer_base_reward >= 1.0 else 0.0
        format_reward = max(0.0, min(0.5, answer_base_reward - accuracy))
        decision_anchor = _as_dict(anchors[decision_rows[0]])
        answer_anchor = _as_dict(anchors[answer_row])
        tool_reward = float(step_rewards[tool_row]) if tool_row is not None else 0.0

        low_tokens = int(decision_anchor.get("vision_tokens_low", 0))
        crop_tokens = int(answer_anchor.get("vision_tokens_crop", 0)) if used_tool else 0
        full_tokens = int(decision_anchor.get("vision_tokens_full", 0))
        processed_tokens = sum(
            int(_as_dict(anchors[index]).get("vision_tokens_step_processed", 0))
            for index in row_indices
        )
        # ``uid`` is generated by verl-agent in blocks of env.rollout.n. That is
        # correct for repeated training rollouts, but validation does not repeat
        # prompts and would therefore group unrelated questions. The environment's
        # stable sample id is the actual prompt-group identity in both modes.
        group_id = str(decision_anchor.get("sample_id", group_ids[answer_row]))
        reward = TrajectoryReward(
            trajectory_id=trajectory_id,
            group_id=group_id,
            accuracy=accuracy,
            format_reward=format_reward,
            used_tool=used_tool,
            tool_reward=tool_reward,
            tool_reward_eligible=bool(decision_anchor.get("tool_reward_eligible", False)),
        )
        reward_records.append(reward)
        partial.append(
            TrajectoryView(
                row_indices=tuple(row_indices),
                tool_row=tool_row,
                answer_row=answer_row,
                reward=reward,
                vision_tokens_low=low_tokens,
                vision_tokens_crop=crop_tokens,
                vision_tokens_acquired=low_tokens + crop_tokens,
                vision_tokens_processed=processed_tokens,
                vision_tokens_full=full_tokens,
            )
        )

    completed = assign_dtpo_rewards_and_advantages(
        reward_records,
        balance_penalty=float(dtpo_config.balance_penalty),
        balance_threshold=float(dtpo_config.balance_threshold),
        epsilon=float(dtpo_config.advantage_epsilon),
    )
    reward_by_id = {record.trajectory_id: record for record in completed}
    return [
        TrajectoryView(
            row_indices=view.row_indices,
            tool_row=view.tool_row,
            answer_row=view.answer_row,
            reward=reward_by_id[view.reward.trajectory_id],
            vision_tokens_low=view.vision_tokens_low,
            vision_tokens_crop=view.vision_tokens_crop,
            vision_tokens_acquired=view.vision_tokens_acquired,
            vision_tokens_processed=view.vision_tokens_processed,
            vision_tokens_full=view.vision_tokens_full,
        )
        for view in partial
    ]
